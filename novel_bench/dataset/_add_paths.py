def patch(path: Path, mapping: dict[str, tuple[list[str], list[dict]]]) -> int:
    text = path.read_text(encoding="utf-8")
    data = yaml.safe_load(text) or {}
    done = 0
    for case in data.get("cases") or []:
        cid = str(case.get("id") or "")
        if cid not in mapping:
            continue
        hard, alts = mapping[cid]
        gt = case.get("ground_truth") or {}
        if gt.get("hard") and gt.get("alternatives"):
            continue                      # 已经补过，跳过（可重复执行）
        # 1) hard 插在 `    ground_truth:` 之后
        i = text.index(f"  - id: {cid}\n")
        j = text.index("    ground_truth:\n", i)
        ins = j + len("    ground_truth:\n")
        if not gt.get("hard"):
            text = text[:ins] + hard_block(hard) + text[ins:]
            j = text.index("    ground_truth:\n", i)
            ins = j + len("    ground_truth:\n")
        # 2) alternatives 追加到本 case 末尾（下一个 `  - id:` 之前）
        try:
            nxt = text.index("\n  - id: ", ins)
            end = nxt + 1
        except ValueError:
            end = len(text.rstrip("\n")) + 1
            text = text.rstrip("\n") + "\n"
        if not gt.get("alternatives"):
            text = text[:end] + alt_block(alts) + text[end:]
        done += 1
    path.write_text(text, encoding="utf-8")
    return done


def main() -> int:
    total = 0
    for f in sorted(WORKS.glob("*.yaml")):
        n = patch(f, DATA)
        if n:
            print(f"{f.name}: 补了 {n} 个用例", flush=True)
            total += n
    print(f"\n共补 {total} 个用例")
    return 0


if __name__ == "__main__":
    sys.exit(main())
