def _fmt_list(items: list[str], indent: str) -> str:
    return "".join(f"{indent}- {x}\n" for x in items)


def _fmt_block(text: str, indent: str) -> str:
    body = "\n".join(indent + ln if ln.strip() else "" for ln in text.strip().splitlines())
    return f"{indent}|\n{body}\n"


def hard_block(items: list[str]) -> str:
    return "      hard:\n" + _fmt_list(items, "        ")


def alt_block(alts: list[dict]) -> str:
    out = "      alternatives:\n"
    for a in alts:
        out += f"        - stance: {a['stance']}\n"
        if a.get("why_valid"):
            out += f"          why_valid: {a['why_valid']}\n"
        if a.get("beats"):
            out += "          beats:\n" + _fmt_list(a["beats"], "            ")
        if a.get("excerpt"):
            out += "          excerpt: " + _fmt_block(a["excerpt"], "            ")
    return out


