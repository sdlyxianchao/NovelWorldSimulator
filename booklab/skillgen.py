def safe_name(s: str, limit: int = 24) -> str:
    """把书名变成能当目录名的样子（**只删非法字符，不改字**）。
        English:
    Turn the book title into something usable as a directory name (**only remove illegal characters,
    don't change the characters**).
    """
    t0 = _BAD.sub('', str(s or '').strip())
    t0 = ' '.join(t0.split())
    return t0[:limit] or '未命名'


