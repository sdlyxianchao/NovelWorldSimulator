def dir_for(title: str, root: Path | None = None) -> Path:
    """某本书的技能目录（**不判断存不存在**）。
        English:
    The skill directory of a given book (**doesn't check existence**).
    """
    return book_root(root) / safe_name(title)


def next_dir(name: str, root: Path | None = None) -> Path:
    """下一个可用的包目录（同名已存在时进 v2 / v3…）。

    ⚠ 只有在**不打算更新已有包**时才该用它 —— 正常路径见 `plan_target()`：
      同一本书再拆一次，默认是**强化更新**（用户 2026-10-10：
      *"每拆一本书，就看下有类似 skill 存在吗？如果有就强化更新，没有就创建"*），
      而不是新开一个 v2。
    
        English:
    The next available package directory (goes to v2 / v3... if the same name already exists).
        ⚠ Only use it when **you don't intend to update an existing package** -- for the normal path see `plan_target()`:
          Splitting the same book again defaults to **strengthen update** (user 2026-10-10:
          *"Each time you split a book, check if a similar skill exists? If so strengthen-update, otherwise create"*),
          rather than starting a new v2.
    """
    root = book_root(root)
    base = safe_name(name)
    first = root / base
    if not first.exists():
        return first
    for i in range(2, 100):
        p = root / f'{base}·v{i}'
        if not p.exists():
            return p
    return root / f'{base}·v99'


