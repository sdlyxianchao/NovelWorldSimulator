# -*- coding: utf-8 -*-
"""**把拆解结果变成技能包**（写进 `skills/`）。

为什么是 SKILL 而不是新造一种文件
--------------------------------
`skills/` 已经是这个项目的**技能机制**：`SKILL.md` + frontmatter + 注册表
（`skills/registry.py`），现有的八个考据技能（中医药方常识、兵器甲胄…）就走这条路。
拆书产出的是同一类东西 —— **一份"遇到某类情况该怎么写"的可查材料** ——
所以放进同一个机制，而不是再发明一套。

两类技能（同一个目录，`分类` 字段分）
------------------------------------
| 分类 | 谁写的 | 什么时候用 |
|---|---|---|
| `历史考据`（现有八个） | 人写的 | 写到郎中/兵器/律法时**查事实** |
| **`拆书经验`**（本模块产出） | 拆书功能生成 | 写某类故事时**学写法** |

frontmatter 里两个字段是**给匹配用的**（现有技能没有，拆书技能必须有）
------------------------------------------------------------------
* `适用类型` —— 这份经验适用于什么类型的书（`主题材` / `结构轴` 各自一串词）。
  拿它跟当前书的**类型卡**比，命中越多越该被引用。
* `特点` —— 这本书的可辨认标签（"群像""反差人设""双强"…）。
  类型卡没有的词，靠它在"这本书和那本书像不像"上再补一层。

⚠ 覆盖与版本：同一本书拆第二次时，**旧包不动、版本进新目录**
  （`书拆·<书名>` → `书拆·<书名>·v2`）—— 与"故事文档版本自增不覆盖"同一条规矩：
  作者可能拆了两遍想对比，覆盖掉就再也比不了了。

⚠ 版权：写进正文的**只有做法**（`怎么做`/`什么时候用`），
  `这本书的例子` 那条**只作证、不作内容**（一句话说出处，不含情节）。
  判据会查产物里有没有成段引用原文。

English:
**Turn the dismantling result into a skill package** (write into `skills/`).
Why SKILL instead of inventing a new kind of file
--------------------------------
`skills/` is already this project's **skill mechanism**: `SKILL.md` + frontmatter + registry
(`skills/registry.py`), the existing eight research skills (common knowledge of Chinese medicine
prescriptions, weapons and armor...) go this path.
What book dismantling produces is the same kind of thing -- **a referenceable piece of material
for "how to write when encountering a certain type of situation"** --
so put it into the same mechanism, rather than inventing another set.
Two kinds of skills (same directory, separated by the `分类` field)
------------------------------------
| Category | Who writes it | When to use |
|---|---|---|
| `历史考据` (the existing eight) | human-written | **look up facts** when writing about doctors/weapons/law |
| **`拆书经验`** (produced by this module) | generated by the book-dismantling feature | **learn the writing method** when writing a certain type of story |
The two fields in frontmatter are **for matching** (existing skills do not have them,
book-dismantling skills must have them)
------------------------------------------------------------------
  Compare it with the current book's **type card**; the more hits, the more it should be cited.
  For words not in the type card, use it to add another layer on "is this book like that book".
⚠ Coverage and versions: when splitting the same book a second time, **don't touch the old
package, put the version in a new directory**
  The author may have split it twice to compare; overwriting makes comparison impossible forever.
  The `这本书的例子` entry **only serves as evidence, not content** (state the source in one sentence, no plot).
  The criterion checks whether the artifact contains paragraph-length quotes from the original text.
"""
