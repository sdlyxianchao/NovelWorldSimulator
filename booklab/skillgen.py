# ══════════════════════════════════════════════════════════════
#  专名泄漏门（反抄袭的**机械**检查）
# [EN] Proper-noun leakage gate (the **mechanical** anti-plagiarism check)
# ══════════════════════════════════════════════════════════════
#: 抽象字段 —— **这些字段里不许出现这本书的专名**（机制卡要能脱离这本书读懂）
# [EN] : Abstract fields -- **proper nouns of this book must not appear in these fields** (the
# [EN] mechanism card must be understandable detached from this book)
ABSTRACT_FIELDS: tuple[str, ...] = (
    '读者想看什么', '情绪链', '戏剧单元', '怎么做',
    '什么时候用', '为什么管用', '可替换项',
)
#: 中文称谓/身份词后缀 —— 用来判断"箭头左边是不是一个专名"。
#: ⚠ 这张表是**本项目自己整理**的（中式称谓），不是抄来的。
# [EN] : Chinese appellation/identity-word suffixes -- used to judge "whether the left side of the
# [EN] arrow is a proper noun".
# [EN] : ⚠ This table is **compiled by this project itself** (Chinese-style appellations), not copied
# [EN] from somewhere.
_ROLE_SUFFIX = ('掌柜', '老板', '老爷', '公子', '先生', '姑娘', '夫人', '大人',
                '师父', '师兄', '道长', '和尚', '秀才', '相公', '娘子', '婆婆',
                '员外', '老爷', '夫人', '大王', '将军', '太守', '县令')


def _is_specific(token: str, book_title: str, banned: set[str]) -> bool:
    """这个箭头左边**像不像专名**（本项目自己的判据，三条取或）。

    1. 就是书名 / 书名的一部分；
    2. 出现在该卡自己的 `不可照搬` 里（**模型自己点名的专名最权威**）；
    3. 带中式称谓后缀（"王掌柜""陈公子"）。
    
        English:
    Whether the left side of this arrow **looks like a proper noun** (this project's own criterion,
    any of three).
        1. It is the book title / part of the book title;
        2. It appears in that card's own `不可照搬` (**proper nouns the model itself named are the most authoritative**);
    """
    t = str(token or '').strip().strip('「」《》""\'')
    if not t or len(t) > 8:
        return False
    if book_title and (t in book_title or book_title in t):
        return True
    if t in banned:
        return True
    return len(t) >= 2 and any(t.endswith(s) for s in _ROLE_SUFFIX)


def leak_check(d: Digest) -> tuple[list[str], list[str]]:
    """专名泄漏门：返回 `(errors, warnings)`。

    ★★ 这一条是这轮借鉴里**最值得带走的想法**（出处见 `theory.GATES` 的注释）：
      它把"反抄袭"从**事后查有没有抄**变成**生成时的格式要求** ——
      `可替换项` 必须写「功能位→任意X」，写成「专名→任意X」立刻能被机械判出来。
      事后查永远查不全：一张抽象得不够的卡，字面上一个专名都没有，
      你没法用任何规则把它抓出来。

    ⚠ **探测不到专名名单时报 warning，不静默通过**（照 oh-story 的规矩）：
      名单来自该卡自己的 `不可照搬` 字段 —— 它是空的（门禁缺失），
      那就等于**这次没查**，必须说出来。
    
        English:
    Proper-noun leak gate: returns `(errors, warnings)`.
        ★★ This one is **the most worth-taking idea** from this round of borrowing (for sources see the comment on `theory.GATES`):
          It turns "anti-plagiarism" from **checking after the fact whether something was copied** into **a format requirement at generation time** --
          `可替换项` must be written as "function slot->any X"; writing it as "proper noun->any X" can be mechanically detected immediately.
          Post-hoc checking never catches everything: a card that isn't abstract enough may literally have no proper noun at all,
          and you can't catch it with any rule.
        ⚠ **When no proper-noun list can be detected, raise a warning, don't silently pass** (per oh-story's rule):
          The list comes from that card's own `不可照搬` field -- if it's empty (gate missing),
          that means **this time nothing was checked**, and you must say so.
    """
    errors: list[str] = []
    warnings: list[str] = []
    book = str(d.brief.title or '').strip()
    no_name_cards: list[str] = []
    for m in d.modules:
        nm = str(m.get('名称') or '?')
        banned = {str(x).strip() for x in (m.get('不可照搬') or []) if str(x).strip()}
        if not banned:
            no_name_cards.append(nm)
        else:
            # ① 抽象字段里出现「不可照搬」点名过的专名 → 泄漏
            # [EN] ① A proper noun named by 「不可照搬」 appears in an abstract field -> leakage
            for fld in ABSTRACT_FIELDS:
                text = ' '.join(m.get(fld) or []) if isinstance(m.get(fld), list) \
                    else str(m.get(fld) or '')
                for b in banned:
                    if b and b in text:
                        errors.append(f'「{nm}」的 `{fld}` 里出现了 `不可照搬` 点名的 '
                                      f'「{b}」—— 专名不许出现在机制字段里')
        # ② 抽象字段里出现书名
        # [EN] ② The book title appears in an abstract field
        if book:
            for fld in ABSTRACT_FIELDS:
                text = ' '.join(m.get(fld) or []) if isinstance(m.get(fld), list) \
                    else str(m.get(fld) or '')
                if book in text:
                    errors.append(f'「{nm}」的 `{fld}` 里出现了书名「{book}」')
        # ③ `可替换项` 的箭头左边像专名（该写功能位，不该写人名/地名）
        # [EN] ③ The left side of the arrow in `可替换项` looks like a proper noun (should write a function slot,
        # [EN] not a person/place name)
        for item in (m.get('可替换项') or []):
            s = str(item or '')
            if '→' not in s:
                # 写成「功能位→任意X」是本项目对格式的硬要求（见 theory.REPLACE_ARROW）
                # [EN] Writing it as "function slot->any X" is this project's hard requirement for the format (see
                # [EN] theory.REPLACE_ARROW)
                errors.append(f'「{nm}」的 `可替换项` 「{s[:24]}」没有用 `→` 写；'
                              f'要写成「功能位→任意X」')
                continue
            left = s.split('→', 1)[0]
            if _is_specific(left, book, banned):
                errors.append(f'「{nm}」的 `可替换项` 左边是专名「{left.strip()}」'
                              f'—— 要写**功能位**（如"欺压者→任何压制主角的人"）')
    if no_name_cards:
        warnings.append('这些卡没写 `不可照搬`，**专名泄漏这次没查**（不是查过没问题）：'
                        + '、'.join(no_name_cards[:4]))
    return errors, warnings


def _merge(d: Digest, old: dict) -> tuple[Digest, list[str]]:
    """把新拆的结果**并进**已有的一份（用户要的"强化更新"）。

    返回 `(合并后的 Digest, 变了什么)`。规则：

    · **模块按名称去重**：同名保留**新的**（重新拆过 = 更了解这本书了），
      并记下哪几条是这一轮**新增**的；
    · `节奏 / 人设 / 语言 / 不适合 / 适用`：新的非空就覆盖，空的保留旧的；
    · **标签求并集**（多拆一次能发现新标签，丢掉旧的没有道理）。
    
        English:
    **Merge** the new dismantle result **into** an existing one (the "strengthen update" the user
    wants).
        Return `(merged Digest, what changed)`. Rules:
        · **Modules deduplicated by name**: for the same name keep **the new one** (re-splitting = knowing the book better),
          and record which entries are **newly added** this round;
        · **Tags are unioned** (splitting more can discover new tags; discarding the old ones makes no sense).
    """
    from booklab.analyzer import Brief                                 # noqa: PLC0415
    changed: list[str] = []
    old_mods = [m for m in (old.get('modules') or []) if isinstance(m, dict)
                and str(m.get('名称') or '').strip()]
    by_name: dict[str, dict] = {str(m['名称']): m for m in old_mods}
    added: list[str] = []
    for m in d.modules:
        k = str(m.get('名称') or '')
        if k and k not in by_name:
            added.append(k)
        by_name[k] = m
    merged_mods = list(by_name.values())[:8]
    if added:
        changed.append('新增写法：' + '、'.join(added[:6]))
    old_final = old.get('final') if isinstance(old.get('final'), dict) else {}
    new_final = dict(old_final)
    for k in ('节奏', '人设', '语言', '适用'):
        v = (d.final or {}).get(k)
        if str(v or '').strip():
            if old_final.get(k) and old_final.get(k) != v:
                changed.append(f'改写了「{k}」')
            new_final[k] = v
    bad_old = list(old_final.get('不适合') or [])
    bad_new = list((d.final or {}).get('不适合') or [])
    new_final['不适合'] = list(dict.fromkeys([*bad_old, *bad_new]))[:6]
    tags_old = old_final.get('标签') if isinstance(old_final.get('标签'), dict) else {}
    tags: dict[str, list[str]] = {}
    for ax in set(list(tags_old) + list(d.tags)):
        vals = list(dict.fromkeys(list(tags_old.get(ax) or []) + list(d.tags.get(ax) or [])))
        if vals:
            tags[ax] = vals
    if tags and tags != tags_old:
        changed.append('标签有更新')
    new_final['标签'] = tags
    new_final['模块'] = merged_mods
    out = Digest(brief=d.brief or Brief(), book=d.book, scan=d.scan, deep=d.deep,
                 final=new_final, seconds=d.seconds, batches_ok=d.batches_ok,
                 batches_all=d.batches_all, notes=list(d.notes))
    return out, changed


def write(d: Digest, *, root: Path | None = None,
          version: str = '1.0', action: str = 'auto') -> 'Written':
    """把拆解结果写成技能包（**一个包 = 一次拆书，自包含三份**）。

    ```text
    skills/book-dismantle/<书名>/SKILL.md     ← 给程序（Agent 按类型取用）
                                digest.json   ← 给程序（结构化，不解析 md）
                                拆书记录.md   ← 给人（完整报告，含逐章概览）
    ```

    `action`：
      · `'auto'`（默认）—— 先 `find_similar()`：**同一本书 → 更新；同类书 → 强化；
        都没有 → 新建**（用户 2026-10-10 点名要的就是这个行为）；
      · `'new'` —— 强制新建（同名进 v2/v3），给"我想留一份对照"的场合用。

    ⚠ `root` 一律指**技能根**（`skills/`），`book-dismantle/` 这一层由本模块加。
      **别把 `book_root()` 的结果当 `root` 传进来** —— 那会拼成
      `skills/book-dismantle/book-dismantle/<书名>/`（本轮真踩过一次，
      判据 B7b 现在钉着这一条）。

    ⚠ 书名拿不到时**照样写**（用"未命名"）—— 拆都拆完了，因为没填名字就
      丢掉成果是最坏的一种"守规矩"。
    
        English:
    Write the dismantle result as a skill package (**one package = one book dismantle,
    self-contained in three parts**).
        ```text
        skills/book-dismantle/<书名>/SKILL.md     <- for programs (Agent fetches by type)
                                    digest.json   <- for programs (structured, doesn't parse md)
                                    拆书记录.md   <- for humans (full report, with per-chapter overview)
        ```
        `action`:
          · `'auto'` (default) —— first `find_similar()`: **same book → update; similar book → reinforce;
            neither → create new** (this is exactly the behavior the user requested on 2026-10-10);
          · `'new'` —— force create new (same name goes to v2/v3), for the case of "I want to keep a copy for comparison".
        ⚠ `root` always refers to the **skill root** (`skills/`), the `book-dismantle/` level is added by this module.
          **Do not pass the result of `book_root()` as `root`** —— that would concatenate into
          `skills/book-dismantle/book-dismantle/<book name>/` (actually hit this once this round,
          criterion B7b now pins this down).
        ⚠ When the book name cannot be obtained, **still write it** (using "untitled") —— the dismantling is already done; dropping the result
          just because the name wasn't filled in is the worst kind of "following the rules".
    """
    root = root or skills_dir()
    book_root(root).mkdir(parents=True, exist_ok=True)
    title = safe_name(d.brief.title or '未命名')

    # ── 决定：更新已有的 / 强化同类的 / 新建 ──
    # [EN] -- Decision: update existing / strengthen similar / create new --
    target, act, why = (None, 'create', '库里还没有同类拆解')
    if action != 'new':
        target, act, why = find_similar(d, root)
    if target is None:
        target = next_dir(d.brief.title or '未命名', root)
        act, why = 'create', why or '库里还没有同类拆解'

    # ── 更新 / 强化：先把旧的那一份读回来合并 ──
    # [EN] -- Update / strengthen: first read back and merge the old one --
    changed: list[str] = []
    hist: list[dict] = []
    if act in ('update', 'strengthen') and (target / 'digest.json').is_file():
        try:
            old = json.loads((target / 'digest.json').read_text(encoding='utf-8'))
            d, changed = _merge(d, old if isinstance(old, dict) else {})
            hist = list(old.get('history') or []) if isinstance(old, dict) else []
        except Exception as e:                                   # noqa: BLE001
            _LOG.warning('读回旧包失败（改为按新内容重写）：%r', e)
    changed = list(dict.fromkeys(changed))

    target.mkdir(parents=True, exist_ok=True)
    md = target / 'SKILL.md'
    md.write_text(render_skill(d, version=version), encoding='utf-8')
    errs, warns = leak_check(d)
    hist.append({
        'at': time.strftime('%Y-%m-%d %H:%M'),
        'action': act, 'why': why, 'version': version,
        'modules': len(d.modules), 'changed': changed,
    })
    # 机器可读的原始结论（以后"按模块检索"用它，不用去解析 md）
    # [EN] Machine-readable raw conclusion (use it later for "retrieve by module", no need to parse the md)
    try:
        (target / 'digest.json').write_text(
            json.dumps({
                'brief': d.brief.__dict__,
                # ★★★ 2026-10-27 溯源三件套（**专业书当素材用，没有出处就是废纸**）：
                #   ① `kind` —— 这本是按哪条线拆的（写法线 / 素材线）；
                #   ② `deep` —— 精读笔记**全文落盘**（原来只存一个 `deep_count` 数字，
                #      而笔记里的 `出处` 是**唯一的溯源信息**，丢了就没法复核）；
                #   ③ `source` —— 源文件路径与类型（原来 `Book.source` 根本没进 json）。
                # [EN] ★★★ 2026-10-27 traceability trio (**a reference book used as material without
                # [EN] sources is waste paper**): ① `kind` -- which line this was split along (craft /
                # [EN] material); ② `deep` -- the deep-read notes **in full** (only a `deep_count`
                # [EN] number used to be stored, while each note's `出处` is the **only traceability
                # [EN] info**; lose it and nothing can be re-checked); ③ `source` -- the source file
                # [EN] path and kind (`Book.source` never reached the json before).
                'kind': getattr(d, 'kind', 'novel'),
                'deep': d.deep,
                'source': ({
                    'path': str(getattr(d.book, 'source', '') or ''),
                    'kind': str(getattr(d.book, 'source_kind', '') or ''),
                    'units': int(getattr(d.book, 'total_units', 0) or 0),
                } if d.book is not None else None),
                'modules': d.modules,
                'entries': d.entries,
                'final': d.final,
                'coverage': d.coverage,
                # ★ 纯数值的结构计数（不靠模型自评，见 `Digest.counts`）
                # [EN] ★ Purely numerical structural counts (not relying on model self-assessment, see `Digest.counts`)
                'counts': d.counts,
                # ★ 是否**同一本书/同类书**上更新来的（审计要看这个）
                # [EN] ★ Whether it was updated on the **same book/similar book** (audit needs to see this)
                'rebuild': {'action': act, 'why': why, 'changed': changed},
                'history': hist[-12:],
                # ★ 专名泄漏门的结论 —— **不管过没过都写下来**
                # [EN] ★ Conclusion of the proper-noun leakage gate -- **write it down pass or fail**
                'leak_check': {'errors': errs, 'warnings': warns},
                'deep_count': len(d.deep),
                'seconds': round(d.seconds, 1),
                'notes': d.notes,
            }, ensure_ascii=False, indent=2), encoding='utf-8')
    except Exception as e:                                       # noqa: BLE001
        _LOG.warning('写 digest.json 失败（不影响 SKILL）：%r', e)
    # 人读的那一份（完整报告）——放在同一个包里，**自包含**
    # [EN] The human-readable one (full report) -- placed in the same package, **self-contained**
    try:
        from booklab.analyzer import preview_md
        (target / '拆书记录.md').write_text(preview_md(d), encoding='utf-8')
    except Exception as e:                                       # noqa: BLE001
        _LOG.warning('写拆书记录失败（不影响 SKILL）：%r', e)
    _LOG.info('拆书技能包已%s：%s（%d 条写法）', {'create': '写出', 'update': '更新',
              'strengthen': '强化'}.get(act, '写出'), target, len(d.modules))
    return Written(dir=target, skill_md=md, name=safe_name(d.brief.title or '未命名'),
                   version=version, action=act, why=why, changed=changed,
                   leak_errors=errs, leak_warnings=warns)


def reload_registry() -> int:
    """让注册表立刻认出新写的技能包（返回现在有几个）。

    为什么要显式重载：注册表是**带缓存的**（`load(force=False)` 只跑一次）。
    不重载的话，刚拆完在同一个会话里看不到新技能 —— 作者会以为"拆了但没生效"。
    
        English:
    Make the registry immediately recognize the newly written skill package (returns how many there
    are now).
        Why an explicit reload: the registry is **cached** (`load(force=False)` only runs once).
        Without reloading, a newly dismantled skill won't be visible in the same session —— the author will think "it was dismantled but didn't take effect".
    """
    try:
        from skills.registry import skill_registry
        skill_registry.load(force=True)
        return len(skill_registry.all_skills())
    except Exception as e:                                       # noqa: BLE001
        _LOG.warning('技能注册表重载失败（重启后仍会生效）：%r', e)
        return 0
