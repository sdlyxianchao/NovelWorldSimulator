#  复用优先：先找找有没有同一本书 / 同类书（用户点名要的那一步）
# [EN] Reuse first: first look for whether there is the same book / a similar book (the step the user
# [EN] explicitly asked for)
# ══════════════════════════════════════════════════════════════
#: 「同类」的判定：受控标签**重合的轴数**下限 + **必须命中一个核心轴**。
# [EN] : Criterion for "similar": lower bound on **number of overlapping axes** of controlled tags +
# [EN] **must hit a core axis**.
#:
#: ★ 为什么不是"重合 ≥2 轴"：真实数据是**稀疏**的 —— 一本书常常只标到
#:   「题材」一个值（模型拿不准的轴会整轴不写，这是我们要的）。门槛设成 2
#:   会导致"永远是新建"：拆得越多，互相越不认。而**题材相同 + 核心轴命中**
#:   才是"同类书"最实用的判据（悬疑书之间当然该共享经验）。
# [EN] : ★ Why not "overlap >= 2 axes": real data is **sparse** -- a book often only tags
# [EN] : one value for "genre" (axes the model is unsure about are simply left out entirely, which is
# [EN] what we want). Setting the threshold to 2
# [EN] : causes "always create new": the more dismantling is done, the less they recognize each other.
# [EN] Whereas **same genre + core axis hit**
# [EN] : is the most practical criterion for "similar books" (mystery books should of course share
# [EN] experience with each other).
#:
#: ★ 为什么必须命中**核心轴**：只在「适用阶段=中段」上撞一个值不算同类 ——
#:   那会让"言情中段"和"悬疑中段"被当成一回事。
# [EN] : ★ Why a **core axis** hit is mandatory: colliding on just one value for "applicable
# [EN] stage=middle section" does not count as similar --
# [EN] : that would make "romance middle section" and "mystery middle section" be treated as the same
# [EN] thing.
SAME_KIND_MIN_AXES = 1

#: 核心轴（与 `booklab/theory.CORE_AXES` **必须一致** —— 那边是写入侧判定，
#: 这里是"同类书"判定；判据会核对两处）。在函数外先取一份，免得在循环里反复 import。
# [EN] : Core axes (must **match** `booklab/theory.CORE_AXES` -- that side is the write-side judgment,
# [EN] : this side is the "similar books" judgment; the criteria checks both places). Fetch a copy
# [EN] outside the function first, to avoid repeated imports inside the loop.
from booklab.theory import CORE_AXES as T_CORE  # noqa: E402


def _existing_packs(root: Path | None = None) -> list[tuple[Path, dict]]:
    """扫一遍已有的拆书包 → `[(目录, digest.json 内容)]`（读不出来就跳过）。
        English:
    Scan existing dismantle packages -> `[(directory, digest.json content)]` (skip if unreadable).
    """
    out: list[tuple[Path, dict]] = []
    base = book_root(root)
    if not base.is_dir():
        return out
    for d in sorted(base.iterdir()):
        if not d.is_dir():
            continue
        f = d / 'digest.json'
        if not f.is_file():
            continue
        try:
            data = json.loads(f.read_text(encoding='utf-8'))
        except Exception:                                        # noqa: BLE001
            continue
        if isinstance(data, dict):
            out.append((d, data))
    return out


def find_similar(d: Digest, root: Path | None = None) -> tuple[Path | None, str, str]:
    """找**同一本书**或**同类书**已有的包。

    返回 `(目录, 动作, 理由)`：
      · 同名书 → `('update', '同一本书，已有一份（<目录>）')`
      · 同类书 → `('strengthen', '同类书：与《X》在 <轴> 上重合')`
      · 都没有 → `(None, 'create', '库里还没有同类拆解')`

    ★ 注意这里**只提议、不自动改** —— 真正的合并写盘在 `write()` 里，
      而 `write()` 会把"改了哪一份、加了什么"写进包的更新记录。
      （本项目的铁律：静默改写用户的东西是不可接受的。）
    
        English:
    Find existing packages for **the same book** or **the same type of book**.
        Return `(directory, action, reason)`:
        ★ Note: here it **only proposes, doesn't auto-modify** -- the actual merge and write-to-disk happens in `write()`,
          and `write()` records "which one was modified, what was added" into the package's update log.
          (This project's iron rule: silently rewriting the user's stuff is unacceptable.)
    """
    title = safe_name(d.brief.title or '未命名')
    packs = _existing_packs(root)
    # ① 同一本书：目录名相同（或目录名是它的 vN）
    # [EN] ① Same book: identical directory name (or the directory name is its vN)
    for p, _data in packs:
        if p.name == title or p.name.startswith(f'{title}·v'):
            return p, 'update', f'同一本书已有一份（{p.name}）'
    # ② 同类书：受控标签重合轴数
    # [EN] ② Similar book: number of overlapping axes of controlled tags
    mine = d.tags
    if not mine:
        return None, 'create', '库里还没有同类拆解（本次也没拿到受控标签）'
    best: tuple[int, Path, list[str]] | None = None
    for p, data in packs:
        theirs = (data.get('final') or {}).get('标签')
        if not isinstance(theirs, dict):
            continue
        shared = [ax for ax in mine
                  if ax in theirs and set(mine[ax]) & set(theirs.get(ax) or [])]
        # 必须命中**核心轴**（只撞"适用阶段"不算同类）
        # [EN] must hit a **core axis** (only colliding on "applicable stage" does not count as similar)
        if not any(ax in T_CORE for ax in shared):
            continue
        if len(shared) >= SAME_KIND_MIN_AXES and (best is None or len(shared) > best[0]):
            best = (len(shared), p, shared)
    if best:
        _n, p, shared = best
        return p, 'strengthen', f'同类书：与 {p.name} 在「{"、".join(shared)}」上重合'
    return None, 'create', '库里还没有同类拆解'


def _bullets(items: list[str], *, empty: str = '（没写这一条）') -> str:
    rows = [f'- {x}' for x in (items or []) if str(x).strip()]
    return '\n'.join(rows) if rows else empty


def render_skill(d: Digest, *, version: str = '1.0') -> str:
    """把拆解结果渲染成一份 `SKILL.md`（frontmatter + 正文）。

    ★ 2026-10-27：专业书走**另一份渲染**（`_render_skill_ref`）——
      它写的是"素材条目 + 出处"，不是"写法模块"。
      硬套小说那份会写出"共 0 条可复用写法""输出：可照着执行的写法"，
      读的人只会以为**这本书没拆出东西**。

        English:
    Render the dismantle result into a `SKILL.md` (frontmatter + body).
        ★ 2026-10-27: reference books take **a different render** (`_render_skill_ref`) -- it writes
        "material entries + sources", not "craft modules". Force-fitting the novel one produces
        "0 reusable crafts", "output: executable craft", and a reader who concludes **this book
        yielded nothing**.
    """
    if getattr(d, 'is_ref', False):
        return _render_skill_ref(d, version=version)
    b = d.brief
    title = b.title or '（未命名）'
    # 触发关键词：书名 + 类型 + 模块名 —— 前两个让它"同类书找得到"，
    # 模块名让它"问到某件事时也找得到"（比如"钩子""反差"）。
    # [EN] Trigger keywords: book title + type + module name -- the first two let it be "found by similar
    # [EN] books",
    # [EN] the module name lets it "also be found when a certain thing is asked about" (e.g. "hook"
    # [EN] "contrast").
    kws: list[str] = []
    for x in (title, b.genre):
        for w in re.split(r'[·、,，/\s]+', str(x or '')):
            w = w.strip()
            if len(w) >= 2 and w not in kws:
                kws.append(w)
    for m in d.modules:
        nm = str(m.get('名称') or '').strip()
        if nm and nm not in kws:
            kws.append(nm)
    kws = kws[:24]

    gate_ok, gate_all = d.gate_stats
    fm = ['---',
          f'名称: {PREFIX}{safe_name(title)}',
          f'版本: {version}',
          f'分类: {CATEGORY}',
          # ★ 门禁计数是**机械算出来的**，不是手写的（oh-story 那条「计数不手写」纪律）。
          # [EN] ★ The gate counts are **computed mechanically**, not hand-written (the oh-story discipline of
          # [EN] "counts are not hand-written").
          f'门禁: {gate_ok}/{gate_all}',
          '触发关键词:']
    fm += [f'  - {k}' for k in kws]
    fm += [f'用途: 写「{b.genre or "同类"}」这一类故事时的写法参考'
           f'（拆自《{title}》，共 {len(d.modules)} 条可复用写法）',
           '输入: 一个正在写的情节 / 人物 / 节奏问题',
           '输出: 可照着执行的写法（怎么做 · 什么时候用 · 为什么管用）',
           '调用工具: []',
           # ★ 下面两个字段是**给匹配用的**（现有技能没有）
           # [EN] ★ The following two fields are **for matching** (existing skills do not have them)
           '适用类型:',
           f'  题材: {b.genre or "（未标）"}',
           '  备注: 类型卡命中时优先引用这一份',
           '特点:']
    for m in d.modules[:6]:
        fm.append(f'  - {m.get("名称")}')
    # ★ 受控标签（值取自 `theory.TAG_VALUES` ≡ `标签词表.md`）——
    #   写成嵌套 YAML 的 `轴: [值]` 形式，好读也好解析。
    #   ⚠ 标签**不进 `触发关键词`**：那一栏走的是子串匹配，把"悬疑"塞进去会让
    #     任何提到"悬疑"的问题都命中这一份；标签走的是**精确命中 + 核心轴加权**，
    #     两条路分开才不会互相污染（见 `registry.score` 与 `store.match`）。
    # [EN] ★ Controlled tags (values taken from `theory.TAG_VALUES` ≡ `标签词表.md`) --
    # [EN] written in the nested YAML `axis: [value]` form, easy to read and easy to parse.
    # [EN] ⚠ Tags **do not go into `触发关键词`**: that column uses substring matching, stuffing "suspense" into
    # [EN] it would make
    # [EN] any question mentioning "suspense" hit this one; tags use **exact hit + core axis weighting**,
    # [EN] keeping the two paths separate avoids mutual pollution (see `registry.score` and `store.match`).
    if d.tags:
        fm.append('标签:')
        for ax, vals in d.tags.items():
            fm.append(f'  {ax}: [{", ".join(vals)}]')
    fm += ['---', '']

    body: list[str] = [f'# {PREFIX}{safe_name(title)}', '']
    if b.genre:
        body.append(f'**适用**：{b.genre}')
    if d.final.get('适用'):
        body.append(f'**最值得谁参考**：{d.final["适用"]}')
    if b.good:
        body.append(f'**作者认为它好在**：{b.good}')
    if d.book is not None:
        body.append(f'**拆自**：{d.book.n} 章（粗扫 {d.coverage}，'
                    f'精读 {len(d.deep)} 条笔记）')
    body += ['', '> 下面写的是**做法**，不是这本书的情节。',
             '> 用的时候照"怎么做"执行，"这本书的例子"只用来确认你理解对了。', '']

    body += ['## 一、能拿走的写法', '']
    if not d.modules:
        body += ['> 这一轮没归纳出可复用的写法 —— 见文末「这一轮的说明」。', '']
    for i, m in enumerate(d.modules, 1):
        body.append(f'### {i}. {m["名称"]}')
        body.append('')
        # ★ 2026-10-10：EM 五门禁字段（跨书复用靠它们，见 `theory.GATES`）。
        #   渲染顺序刻意"先机制、后工艺"：先让人看清这一招**脱离这本书**是什么样子，
        #   再看怎么执行 —— 反过来的话读者会先记住情节，之后再看抽象层就用不上了。
        # [EN] ★ 2026-10-10: EM five gate fields (cross-book reuse relies on them, see `theory.GATES`).
        # [EN] The rendering order deliberately goes "mechanism first, craft second": first let people clearly
        # [EN] see what this move looks like **detached from this book**,
        # [EN] then see how to execute it -- the other way around, the reader first remembers the plot, and
        # [EN] afterwards the abstract layer is useless to them.
        if m.get('读者想看什么'):
            body.append(f'**读者想看什么**：{m["读者想看什么"]}')
            body.append('')
        if m.get('情绪链'):
            body.append(f'**情绪链**：{m["情绪链"]}')
            body.append('')
        if m.get('戏剧单元'):
            body.append(f'**戏剧单元**（去掉素材后的结构）：{m["戏剧单元"]}')
            body.append('')
        if m.get('可替换项'):
            body.append('**可替换项**（这些位置可以整体换掉）：')
            body.append('')
            body.append(_bullets(list(m['可替换项'])))
            body.append('')
        if m.get('不可照搬'):
            body.append('**不可照搬**（跟着搬会出事）：')
            body.append('')
            body.append(_bullets(list(m['不可照搬'])))
            body.append('')
        body.append(f'**怎么做**：{m["怎么做"]}')
        body.append('')
        if m.get('什么时候用'):
            body.append(f'**什么时候用**：{m["什么时候用"]}')
            body.append('')
        if m.get('为什么管用'):
            body.append(f'**为什么管用**：{m["为什么管用"]}')
            body.append('')
        if m.get('这本书的例子'):
            body.append(f'**这本书的例子**：{m["这本书的例子"]}')
            body.append('')

    f = d.final or {}
    for key, label, hint in (
            ('节奏', '二、节奏', '压多长、爆多大、单元多长 —— 可以当模板用'),
            ('人设', '三、立人的套路', '不是某个人物的设定，是作者**立人**的共同手法'),
            ('语言', '四、文风', '具体到能照着写，不是"文笔好"这类评价')):
        if f.get(key):
            body += [f'## {label}', '', f'*{hint}*', '', f[key], '']

    if f.get('不适合'):
        body += ['## 五、换本书就不能用的', '',
                 '> 这一节和上面同样重要 —— **知道什么不能照搬，才不会学坏**。', '']
        body.append(_bullets(list(f['不适合'])))
        body.append('')

    if d.tags:
        body += ['## 六、受控标签', '',
                 '> 这些都是从**固定词表**里选的（见 `skills/book-dismantle/标签词表.md`）。',
                 '> 它们决定"以后写什么书时该翻出这一份"——',
                 '> 词表是**写入侧与查询侧共用**的一张表，所以别随手造新词。', '']
        for ax, vals in d.tags.items():
            body.append(f'- **{ax}**：{"、".join(vals)}')
        body.append('')

    body += ['## 七、这是怎么拆出来的', '',
             f'四道工序：分章 → 粗扫（{d.coverage}）→ 精读 {len(d.deep)} 条笔记 → 归纳。',
             f'用时 {d.seconds:.0f} 秒。'
             + (f' 门禁齐全 {gate_ok}/{gate_all} 条。' if gate_all else ''), '']
    if d.notes:
        body += ['**这一步的说明（照实记）**：', '', _bullets(d.notes), '']
    if d.brief.focus:
        body += [f'**作者点名要拆的**：{d.brief.focus}', '']
    return '\n'.join(fm + body)


def _render_skill_ref(d: Digest, *, version: str = '1.0') -> str:
    """专业书 / 资料书的 `SKILL.md`：**素材条目 + 出处**。

    ★ 与小说那份的**三个不一样**（每一样都是被"专业书不是小说"逼出来的）：

      1. 产物是**条目**不是模块 —— 一条 = 一个能被查证、能被写进故事的事实；
      2. **每条都带出处**（第几章）—— 没出处的条目不能当素材引用，
         所以这里照实标出"未写出处"，不替它编；
      3. 门禁是 `REF_GATES`（能怎么用 / 可信度 / 边界条件 / 可替换项 / 不可照搬），
         不是小说的"情绪链 / 戏剧单元"。

    ⚠ 触发关键词里放**条目名**：这样"问到某件事"时能直接找到这本
       （比如写一场"盖房子"的戏，问"举架"就能命中拆自建筑史的那本）。

        English:
    The `SKILL.md` for a reference / specialist book: **material entries + sources**.
        ★ Three differences from the novel one (each forced by "a reference book is not a novel"):
          1. the product is **entries**, not modules -- one entry = one checkable fact that can be
             written into a story;
          2. **every entry carries a source** (which chapter) -- an entry without one cannot be
             quoted as material, so it is honestly marked "no source given" rather than invented;
          3. the gates are `REF_GATES` (how to use it / reliability / boundary conditions /
             swappable / not transferable), not the novel's "emotional chain / dramatic unit".
        ⚠ Entry names go into the trigger keywords: that way "asking about a thing" finds this book
        (writing a house-building scene, asking "举架" hits the pack split from an architecture
        history).
    """
    from booklab import theory as T
    b = d.brief
    title = b.title or '（未命名）'
    ents = d.entries

    # 触发关键词：书名 + 类型 + **条目名**（问到那件事时也能找到这一本）
    # [EN] Trigger keywords: book title + type + **entry names** (findable when that thing is asked)
    kws: list[str] = []
    for x in (title, b.genre):
        for w in re.split(r'[·、,，/\s]+', str(x or '')):
            w = w.strip()
            if len(w) >= 2 and w not in kws:
                kws.append(w)
    for e in ents[:18]:
        nm = str(e.get('名字') or '').strip()
        if len(nm) >= 2 and nm not in kws:
            kws.append(nm)
    kws = kws[:24]

    gate_ok, gate_all = d.gate_stats
    sourced = sum(1 for e in ents if str(e.get('出处') or '').strip())
    fm = ['---',
          f'名称: {PREFIX}{safe_name(title)}',
          f'版本: {version}',
          f'分类: {CATEGORY}',
          f'门禁: {gate_ok}/{gate_all}',
          '触发关键词:']
    fm += [f'  - {k}' for k in kws]
    fm += [f'用途: 写「{b.genre or "同类"}」这类内容时的**素材参考**'
           f'（拆自《{title}》，共 {len(ents)} 条可查证条目，{sourced} 条带出处）',
           '输入: 一个要写得"像真的"的细节（尺寸 / 规矩 / 叫法 / 年代）',
           '输出: 可引用的素材条目（含出处与边界条件）',
           '调用工具: []',
           # ★ 这一栏是**给匹配用的**：写明它是"素材型"不是"写法型"
           # [EN] ★ This field is **for matching**: it says this is a "material" pack, not a "craft" one
           '适用类型:',
           f'  题材: {b.genre or "（未标）"}',
           '  备注: **素材型**（按专业书那条线拆的，产出是可引用的事实，不是写法）',
           '特点:']
    for e in ents[:6]:
        cat = str(e.get('类别') or '').strip()
        fm.append(f'  - {e.get("名字")}'
                  + (f'（{cat}）' if cat else ''))
    fm += ['---', '']

    body: list[str] = [
        f'# {PREFIX}{safe_name(title)}（素材型）', '',
        f'**来源**：《{title}》　**类型**：{b.genre or "（未标）"}'
        f'　**判定**：{T.REF_GATES and "素材线" or ""}', '',
        '> ⚠ 这是按**专业书**那条线拆的：里面是可查证、可引用的**素材条目**，'
        '不是"写法"。每条都写了出处 —— **没写出处的条目不要直接引用**'
        '（没法复核的东西不能当素材）。', '',
    ]
    use = str(d.final.get('这本书的用法') or '').strip() if isinstance(d.final, dict) else ''
    if use:
        body += ['## 这本书适合喂给什么', '', use, '']

    # 按类别分组（术语 / 事实 / 规矩 / 实例 / 易错）
    # [EN] Group by category (term / fact / rule / case / caveat)
    groups: dict[str, list[dict]] = {}
    for e in ents:
        groups.setdefault(str(e.get('类别') or '其它').strip() or '其它', []).append(e)
    order = ('术语', '事实', '规矩', '实例', '易错')
    keys = [k for k in order if k in groups] + \
           [k for k in groups if k not in order]
    body += [f'## 条目（共 {len(ents)} 条，{sourced} 条带出处）', '']
    for k in keys:
        rows = groups[k]
        body += [f'### {k}（{len(rows)} 条）', '']
        for e in rows:
            nm = str(e.get('名字') or '（无名）').strip()
            src = str(e.get('出处') or '').strip() or '**未写出处**'
            body.append(f'- **{nm}**　`{src}`')
            body.append(f'  {e.get("内容")}')
            tails: list[str] = []
            for g in T.REF_GATES:
                val = str(e.get(g) or '').strip()
                if val:
                    tails.append(f'{g}：{val}')
            if tails:
                body.append('  - ' + '　｜　'.join(tails))
        body.append('')

    bad = d.final.get('不适合') if isinstance(d.final, dict) else None
    if bad:
        if isinstance(bad, str):
            bad = [bad]
        body += ['## 什么情况下不该用这本', '', _bullets(
            [str(x) for x in bad if str(x).strip()]), '']

    body += ['## 这是怎么拆出来的', '',
             '四道工序：分章 → 粗扫（按**信息密度**，不是按情绪）'
             f'（{d.coverage}）→ 精读 {len(d.deep)} 条笔记 → 归纳成条目。',
             f'用时 {d.seconds:.0f} 秒。'
             + (f' 门禁齐全 {gate_ok}/{gate_all} 条。' if gate_all else ''), '']
    if d.notes:
        body += ['**这一步的说明（照实记）**：', '', _bullets(d.notes), '']
    return '\n'.join(fm + body)


