def _sheet_title(ws, text: str, *, size: int = 14) -> int:
    """写一个大标题，返回下一个可用行号（1 起）。
        English:
    Write a big title, return the next available row number (1-based).
    """
    ws.cell(row=1, column=1, value=text).font = _Font(bold=True, size=size)
    return 3


def _write_table(ws, start: int, headers: list[str], rows: list[list]) -> int:
    """写一张表（表头加粗 + 冻结 + 列宽自适应）。返回下一行行号。
        English:
    Write one table (bold header + freeze + auto column width). Return the next row number.
    """
    for c, h in enumerate(headers, 1):
        cell = ws.cell(row=start, column=c, value=h)
        cell.font = _Font(bold=True)
    for r, row in enumerate(rows, start + 1):
        for c, v in enumerate(row, 1):
            ws.cell(row=r, column=c, value=v)
    if rows:
        ws.freeze_panes = ws.cell(row=start + 1, column=1)
    # 列宽：按表头与内容的**显示宽度**取最大值（中文算 2 格）
    # [EN] Column width: take the max of the **display width** of headers and content (Chinese counts as 2
    # [EN] cells)
    for c, h in enumerate(headers, 1):
        w = _disp_width(str(h))
        for row in rows[:200]:
            if c - 1 < len(row):
                w = max(w, _disp_width(str(row[c - 1])))
        ws.column_dimensions[ws.cell(row=start, column=c).column_letter].width = min(46, w + 2)
    return start + len(rows) + 2


def _disp_width(s: str) -> int:
    return sum(2 if ord(ch) > 0x2E80 else 1 for ch in s)


def _Font(**kw):                                                 # noqa: N802
    """延迟取 openpyxl 的 Font（这样本模块能在没装 openpyxl 时被 import）。
        English:
    Lazily fetch openpyxl's Font (so this module can be imported when openpyxl isn't installed).
    """
    from openpyxl.styles import Font
    return Font(**kw)


def build(scope: str | None, out_path: Path, *, lang: str = 'zh',
          since: str | None = None, path: Path | None = None) -> Path:
    """生成 xlsx。返回写出的路径。

    Sheet 顺序（用户要求"第一个一定是总体信息"）：
      ① 总体信息 → ② 按模型 → ③ 按日期 → ④（项目才有）按推演任务
      → ⑤ 按模块 → ⑥ 按 Agent（总表）→ ⑦ 明细
    每张表前面都有一段**简短介绍**（用户要求"包含自己的简单介绍信息"）。
    
        English:
    Generate the xlsx. Return the written path.
        Sheet order (user requires "the first must be Overall info"):
          ① Overall info → ② By model → ③ By date → ④ (only for projects) By simulation task
          → ⑤ By module → ⑥ By Agent (summary table) → ⑦ Detail
        Each table is preceded by a **brief intro** (user requires "contain its own brief intro info").
    """
    from openpyxl import Workbook
    d = collect(scope, lang=lang, since=since, path=path)
    tt = d['totals']
    who = _t(lang, 'scope_project') + f'：{scope}' if scope else _t(lang, 'scope_global')
    wb = Workbook()

    # ① 总体信息
    # [EN] ① Overall info
    ws = wb.active
    ws.title = _t(lang, 'sheet_overview')
    r = _sheet_title(ws, f'{who} · {_t(lang, "sheet_overview")}')
    ws.cell(row=r - 1, column=1, value=_t(lang, 'intro_overview'))
    total_tok = int(tt['in_tok']) + int(tt['out_tok'])
    rows = [
        [_t(lang, 'm_calls'), tt['calls']],
        [_t(lang, 'm_in'), tt['in_tok']],
        [_t(lang, 'm_out'), tt['out_tok']],
        [_t(lang, 'm_total'), total_tok],
        [_t(lang, 'm_cost'), round(float(tt['cost']), 4)],
        [_t(lang, 'm_models'), tt['models']],
        [_t(lang, 'm_modules'), tt['modules']],
        [_t(lang, 'm_agents'), tt['agents']],
        [_t(lang, 'm_range'),
         (f"{tt['first_day']} ~ {tt['last_day']}" if tt['first_day'] else '—')],
        [_t(lang, 'generated'), __import__('time').strftime('%Y-%m-%d %H:%M:%S')],
    ]
    r = _write_table(ws, r, [_t(lang, 'metric'), _t(lang, 'value')], rows)
    ws.cell(row=r, column=1, value=_t(lang, 'note_no_llm'))
    ws.cell(row=r + 1, column=1, value=_t(lang, 'note_estimate'))

    # ②…⑤ 各划分
    # [EN] ②...⑤ Each breakdown
    for by in (U.BY_FOR_PROJECT if scope else U.BY_FOR_GLOBAL):
        label = _by_label(by, lang)
        ws = wb.create_sheet(_t(lang, 'sheet_by', by=label)[:31])
        r = _sheet_title(ws, f'{who} · {_t(lang, "sheet_by", by=label)}')
        ws.cell(row=r - 1, column=1, value=_t(lang, 'intro_by', by=label))
        gs = d['bys'].get(by) or []
        hk = _t(lang, 'h_key', by=label)
        rows = [[g['key'], g['calls'], g['in_tok'], g['out_tok'],
                 g['in_tok'] + g['out_tok'], round(g['cost'], 4),
                 (round(g['cost'] / tt['cost'], 4) if tt['cost'] else 0), g['agents']]
                for g in gs]
        r = _write_table(ws, r, [hk, _t(lang, 'h_calls'), _t(lang, 'h_in'),
                                 _t(lang, 'h_out'), _t(lang, 'h_total'),
                                 _t(lang, 'h_cost'), _t(lang, 'h_share'),
                                 _t(lang, 'h_agents')], rows)

    # ⑥ 按 Agent（总表）
    # [EN] ⑥ By Agent (summary table)
    ws = wb.create_sheet(_t(lang, 'sheet_agents')[:31])
    r = _sheet_title(ws, f'{who} · {_t(lang, "sheet_agents")}')
    ws.cell(row=r - 1, column=1, value=_t(lang, 'intro_agents'))
    rows = [[a['agent'], a['calls'], a['in_tok'], a['out_tok'],
             a['in_tok'] + a['out_tok'], round(a['cost'], 4),
             (round(a['cost'] / tt['cost'], 4) if tt['cost'] else 0)]
            for a in d['agents_all']]
    r = _write_table(ws, r, [_t(lang, 'h_agent'), _t(lang, 'h_calls'),
                             _t(lang, 'h_in'), _t(lang, 'h_out'),
                             _t(lang, 'h_total'), _t(lang, 'h_cost'),
                             _t(lang, 'h_share')], rows)

    # ⑦ 明细
    # [EN] ⑦ Detail
    ws = wb.create_sheet(_t(lang, 'sheet_detail')[:31])
    r = _sheet_title(ws, f'{who} · {_t(lang, "sheet_detail")}')
    ws.cell(row=r - 1, column=1,
            value=_t(lang, 'intro_detail', n=len(d['detail'])))
    import time as _time
    rows = [[_time.strftime('%Y-%m-%d %H:%M:%S', _time.localtime(x['ts'])), x['day'],
             x['project'], x['run'], x['module'], x['agent'] or '（/）', x['model'],
             x['purpose'], x['tier'], x['in_tok'], x['out_tok'],
             round(float(x['cost']), 6)] for x in d['detail']]
    _write_table(ws, r, [_t(lang, 'h_time'), _t(lang, 'h_day'), _t(lang, 'h_project'),
                         _t(lang, 'h_run'), _t(lang, 'h_module'), _t(lang, 'h_agent'),
                         _t(lang, 'h_model'), _t(lang, 'h_purpose'), _t(lang, 'h_tier'),
                         _t(lang, 'h_in'), _t(lang, 'h_out'), _t(lang, 'h_cost')], rows)

    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(str(out_path))
    _LOG.info('用量报告已导出：%s（%d 个 Sheet）', out_path, len(wb.sheetnames))
    return out_path


def default_name(scope: str | None = None, *, lang: str = 'zh') -> str:
    """默认文件名（**ASCII 安全**：项目名里可能有空格与中文，统一换成下划线）。
        English:
    Default filename (**ASCII-safe**: project names may contain spaces and Chinese, uniformly
    replaced with underscores).
    """
    import re as _re
    import time as _time
    who = _re.sub(r'[^\w\-]+', '_', str(scope or ''))[:24] or 'global'
    stamp = _time.strftime('%Y%m%d_%H%M')
    return f'usage_{who}_{lang}_{stamp}.xlsx'
