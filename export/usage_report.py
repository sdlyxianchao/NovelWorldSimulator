def _t(lang: str, key: str, **kw) -> str:
    d = L.get(lang) or L['zh']
    s = d.get(key) or (L['zh'].get(key) or key)
    for k, v in kw.items():
        s = s.replace('{' + k + '}', str(v))
    return s


def _by_label(by: str, lang: str) -> str:
    return U.BY_EN.get(by, by) if lang == 'en' else by


def collect(scope: str | None, *, lang: str = 'zh', since: str | None = None,
            path: Path | None = None, detail_limit: int = 500) -> dict:
    """把要写进 xlsx 的**全部数据**取出来（纯取数，不排版）。

    `scope=None` ⇒ 软件整体；否则是某个项目名。
    
        English:
    Fetch **all data** to be written into the xlsx (pure data fetching, no layout).
        `scope=None` ⇒ whole software; otherwise a project name.
    """
    bys = U.BY_FOR_PROJECT if scope else U.BY_FOR_GLOBAL
    out: dict = {
        'scope': scope, 'lang': lang, 'since': since,
        'totals': U.totals(scope, since=since, path=path),
        'bys': {b: U.groups(scope, b, since=since, path=path) for b in bys},
        'agents_all': [],
        'detail': [],
    }
    # Agent 总表：把每个模型的 Agent 合起来（不区分第二层）
    # [EN] Agent summary table: combine every model's Agent (don't distinguish the second layer)
    agg: dict[str, dict] = {}
    for b in bys:
        for g in out['bys'][b]:
            for a in U.agents(scope, b, g['key'], since=since, path=path):
                row = agg.setdefault(a['agent'], {'agent': a['agent'], 'calls': 0,
                                                  'in_tok': 0, 'out_tok': 0, 'cost': 0.0})
                for k in ('calls', 'in_tok', 'out_tok', 'cost'):
                    row[k] += a[k]
    out['agents_all'] = sorted(agg.values(), key=lambda r: -r['cost'])
    # 明细：不带分组条件的全量（按天取会漏，所以直接查一次）
    # [EN] Detail: full data without grouping conditions (fetching by day would miss entries, so just query
    # [EN] once)
    out['detail'] = _all_detail(scope, since=since, limit=detail_limit, path=path)
    return out


def _all_detail(scope: str | None, *, since: str | None = None, limit: int = 500,
                path: Path | None = None) -> list[dict]:
    w, args = U._where(scope, since)
    args.append(int(limit))
    try:
        conn = U._conn(path)
        try:
            rows = conn.execute(
                'SELECT ts, day, module, project, run, agent, model, purpose, tier,'
                ' in_tok, out_tok, cost FROM usage_log WHERE 1=1' + w
                + ' ORDER BY ts DESC LIMIT ?', args).fetchall()
        finally:
            conn.close()
    except Exception as e:                                       # noqa: BLE001
        _LOG.warning('读明细失败：%r', e)
        return []
    return [dict(r) for r in rows]


